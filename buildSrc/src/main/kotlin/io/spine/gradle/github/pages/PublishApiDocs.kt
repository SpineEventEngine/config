package io.spine.gradle.github.pages

import dokkaHtmlTask
import dokkaJavadocTask
import io.spine.gradle.SpineTaskGroup
import io.spine.gradle.fs.LazyTempPath
import io.spine.gradle.getOrRegister
import io.spine.gradle.github.pages.TaskName.copyHtmlDocs
import io.spine.gradle.github.pages.TaskName.copyJavadocDocs
import io.spine.gradle.github.pages.TaskName.publishApiDocs
import java.io.File
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.Task
import org.gradle.api.tasks.Copy
import org.gradle.api.tasks.TaskContainer
import org.gradle.api.tasks.TaskProvider

/**
 * Registers the `publishApiDocs` task that publishes the API documentation
 * of a particular Gradle project, generated in Javadoc and HTML format.
 *
 * The generated documentation is appended to the `spine.io` site
 * via GitHub Pages by pushing commits to the `gh-pages` branch.
 *
 * The task is not a part of the Maven publication. It is run by the `publish-api-docs.yml`
 * workflow, apart from `publish.yml`, through the `publishApiDocs` task of the root
 * project, which [publishes the documentation of the published modules that apply
 * this plugin][registerAggregate].
 *
 * In order to work, the script needs a `deploy_key_rsa` private RSA key file in the
 * repository root. It is recommended to encrypt it in the repository and then decrypt
 * it on CI upon publication. Also, the script uses the `FORMAL_GIT_HUB_PAGES_AUTHOR`
 * environment variable to set the author email for the commits. The `gh-pages`
 * branch is created automatically if it does not exist yet.
 *
 * NOTE: when changing the value of "FORMAL_GIT_HUB_PAGES_AUTHOR", one also must change
 * the SSH private (encrypted `deploy_key_rsa`) and the public
 * ("GitHub Pages publisher" on GitHub) keys.
 *
 * Another requirement is an environment variable `REPO_SLUG`, which a CI workflow sets,
 * such as the `Publish API docs` GitHub Actions workflow. It points to
 * the repository for which the documentation is published. E.g.:
 *
 * ```
 *      REPO_SLUG: SpineEventEngine/base
 * ```
 *
 * @see PublishApiDocsExtension for the extension that is used to configure
 *      this plugin
 */
class PublishApiDocs : Plugin<Project> {

    /**
     * Root folder of the repository, to which this `Project` belongs.
     */
    internal lateinit var rootFolder: File

    /**
     * The external inputs to include into the publishing.
     *
     * The inputs are evaluated according to [Copy.from] specification.
     */
    private lateinit var includedInputs: Set<Any>

    /**
     * Path to the temp folder used to gather the Javadoc format output (generated by Dokka)
     * before publishing it.
     */
    internal val javadocOutputFolder = LazyTempPath("javadoc")

    /**
     * Path to the temp folder used to gather the HTML documentation
     * generated by Dokka before publishing it.
     */
    internal val htmlOutputFolder = LazyTempPath("html")

    /**
     * Applies the plugin to the specified [project].
     */
    override fun apply(project: Project) {
        val extension = PublishApiDocsExtension.createIn(project)
        project.afterEvaluate {
            registerTasks(extension)
        }
    }

    private fun Project.registerTasks(extension: PublishApiDocsExtension) {
        rootFolder = extension.rootFolder()
        includedInputs = extension.includedInputs()

        tasks.registerCopyJavadoc()
        tasks.registerCopyDokka()

        val publishTask = tasks.registerPublishTask()
        publishTask.configure {
            dependsOn(copyJavadocDocs)
            dependsOn(copyHtmlDocs)
        }
    }

    private fun TaskContainer.registerCopyJavadoc() {
        val inputs = composeJavadocInputs()

        register(copyJavadocDocs, Copy::class.java) {
            group = SpineTaskGroup.name
            description = "Copies generated Javadoc into the GitHub Pages staging folder"
            inputs.forEach { from(it) }
            into(javadocOutputFolder)
        }
    }

    private fun TaskContainer.composeJavadocInputs(): List<Any> {
        val inputs = mutableListOf<Any>()
        inputs.add(dokkaJavadocTask()!!)
        inputs.addAll(includedInputs)
        return inputs
    }

    private fun TaskContainer.registerCopyDokka() {
        val inputs = composeDokkaInputs()

        register(copyHtmlDocs, Copy::class.java) {
            group = SpineTaskGroup.name
            description = "Copies generated Dokka HTML docs into the GitHub Pages staging folder"
            inputs.forEach { from(it) }
            into(htmlOutputFolder)
        }
    }

    private fun TaskContainer.composeDokkaInputs(): List<Any> {
        val inputs = mutableListOf<Any>()

        dokkaHtmlTask()?.let {
            inputs.add(it)
        }
        inputs.addAll(includedInputs)

        return inputs
    }

    /**
     * Registers the [TaskName.publishApiDocs] task of this project, or takes the task
     * that is already registered.
     *
     * In a single-project build, the root project is both the documented project and
     * the owner of [the aggregate][registerAggregate], so whichever of this plugin and
     * `spinePublishing { }` comes first registers the task. The plugin configures it
     * here either way, so that it also publishes the documentation of this project.
     */
    private fun TaskContainer.registerPublishTask(): TaskProvider<Task> {
        val task = getOrRegister(publishApiDocs)
        task.configure {
            group = SpineTaskGroup.name
            description = "Publishes the API documentation to the `gh-pages` branch"
            doLast {
                try {
                    updateGhPages(project)
                } finally {
                    cleanup()
                }
            }
        }
        return task
    }

    private fun cleanup() {
        val folders = listOf(htmlOutputFolder, javadocOutputFolder)
        folders.forEach {
            it.toFile().deleteRecursively()
        }
    }

    internal companion object {

        /**
         * Registers the [TaskName.publishApiDocs] task in the [root] project.
         * The task publishes the API documentation of the [published] projects.
         *
         * The task depends on the `publishApiDocs` task of each of the [published]
         * projects that has one, that is, applies this plugin. A project that applies
         * the plugin, but is not published, such as a module of integration tests,
         * is left out.
         *
         * The task is registered even when none of the projects has the documentation
         * to publish, and then does nothing. This lets the `publish-api-docs.yml`
         * workflow run it in any repository that publishes: Gradle fails on a task
         * that is missing from the build.
         *
         * If [root] applies this plugin itself, as in a single-project build, the task
         * also publishes the documentation of [root], published or not.
         *
         * The plugin registers the task of a project once that project is evaluated,
         * so the tasks to depend on are looked up only when Gradle resolves
         * the dependencies of this task. Repeated calls add their projects to the same
         * task, as `spinePublishing { }` may run more than once in a build.
         */
        fun registerAggregate(root: Project, published: Set<Project>) {
            val task = root.tasks.getOrRegister(publishApiDocs) {
                group = SpineTaskGroup.name
                description = "Publishes the API documentation of the published modules"
            }
            task.configure {
                dependsOn(root.provider {
                    published
                        .filter { it != root && publishApiDocs in it.tasks.names }
                        .map { "${it.path}:$publishApiDocs" }
                })
            }
        }
    }
}
